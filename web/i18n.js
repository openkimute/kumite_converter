// the language to show: ?lang=xx, else the one chosen before, else the browser's first one offered, else English
export function pickLang(stored) {
  const want = [new URLSearchParams(location.search).get('lang'), stored, ...(navigator.languages ?? [navigator.language])];
  for (const w of want) {
    const code = w?.toLowerCase().split(/[-_]/)[0];
    if (code && LANGS[code]) return code;
  }
  return 'en';
}

// `key`'s text in `lang` with `params` filled in (a function as a value: called, for text translated itself)
export function t(lang, key, params = {}) {
  const s = S[lang]?.[key] ?? S.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => {
    const v = params[k];
    return v === undefined ? m : String(typeof v === 'function' ? v() : v);
  });
}

