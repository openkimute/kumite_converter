//! export_gamedata: export Tekken 3 (USA, SLUS-00402) GAMEPLAY DATA to JSON for a re-implementation engine.
//!
//! `t3_convert export_gamedata BIN OUTDIR` writes OUTDIR/gamedata/*.json (plus README.md); the schema is in the
//! Python script's docstring. ANIMATION NAMING (shared with export_gltf): "motion_NNN" = index NNN in
//! anim::find_motions(rec[m+3], h[7], h[8]); "common_NNN" = index in anim::find_motions(rec[279], ...).

use crate::disc::{Game, py_slice};
use crate::gamedata_core::{Exe, read_sequences, write_json};
use crate::gamedata_moves::{Moveset, N_ALIASES, md5_hex};
use crate::gamedata_tables as t;
use anyhow::{Context, Result, bail};
use conv_io::{Ctx, DiscFile, StdDisc, StdFs, join, print_line};
use serde_json::{Value, json};
use std::collections::BTreeMap;

const USAGE: &str = r#"Export Tekken 3 (USA, SLUS-00402) GAMEPLAY DATA to JSON for a re-implementation engine.

usage: t3_convert export_gamedata "Tekken_3_(USA)_(Track 1).bin" OUTDIR

Writes OUTDIR/gamedata/*.json (plus README.md). The consumer never needs the disc or PS1 formats.
Specs: docs/reference/tekken3/engine.md §6-8, §12-13 and docs/reference/tekken3/{move-properties,attack-paths,reactions,camera,ai}.md.
Integers stay integers; raw words are kept next to decoded fields so nothing is lost. Units: game units
(~1 mm, Y down, floor y = 0), frames at 60 fps, angles 4096 (or 65536 where noted) per turn.

"#;

const README: &str = r#"# Tekken 3 gameplay data (JSON)

Generated by `t3_convert export_gamedata` from your own disc image (SLUS-00402).
A re-implementation engine reads only these files plus the glTF/media exports; no PS1 formats.

Conventions: integers everywhere; game units ~1 mm with **Y down** and the floor at y = 0;
60 frames per second; angles are 4096 per turn unless noted (65536 for actor-angle fields such as
reaction pushback angles). Every EXE-derived table carries its PS1 RAM `address` for traceability.

## Files
| File | Contents |
|---|---|
| `movesets/index.json` | model record (71..275 step 4) -> moveset file, moveset id, glb name |
| `movesets/moveset_NN.json` | one per distinct character moveset (NN = moveset id) |
| `movesets/common.json` | common bank, record 279 (no alias table; its dests resolve in the fighter's moveset) |
| `shared.json` | EXE shared cancel lists, motion-input sequences, built-in attack descriptors, direction table |
| `reactions.json` | 633 reaction entries, slot-selection rules, pushback curves, air/throw/close-range tables |
| `rules.json` | health, round time, damage zones, hurt/push sphere radii, counter/juggle/chip/throw rules, the rules kept for some characters and moves (`characters`, `moves`) |
| `roster.json` | characters, 92 selections (char*4+costume), select grid, unlocks, model size percent |
| `stages.json` | stage ids 0-19, glb names, home characters, floor tiling, stage lights |
| `music.json` | BGM table (2 columns), XA table -> `NN.flac` / `cdda_track2.flac` |
| `ai.json` | 30 CPU profiles, spacing, per-moveset parry/canned inputs, handlers (what each routine does and the aliases it compares), the routine's tests of particular move sets and aliases (`rules`), opponent selection rules, the arcade ladder |
| `screens.json` | title, main menu and character select layouts: fonts (glyph places), strings, menu items, select slots, layouts, decorations, portrait descriptors, faces; the menus' system sounds (`sounds`) |
| `scenes.json` | in-engine cut-scenes: the True Ogre scene (arcade overlay 0x800B3CA0): its script, camera, body model choice, fade |
| `sound.json` | sound code table (move sound lists -> SePlay codes), code format, voice rows per character, the sound-list entries the sound player's own code plays (`impact_rules`, `move_sounds`) |
| `camera.json` | sin/atan tables, fight camera constants, intro offsets, situation presets, shake scripts, KO/win/replay |

## Moves
`moves[i]` is move record *i* of the file. A fighter's moves are reached through **aliases**:
`aliases[a] = {bank, move}` where bank `own` = this file's `moves`, `common` = `common.json` moves,
`none` = missing (at match load it is borrowed from the opponent's alias table; if both lack it, alias
0xDC5). Cancel `dest` values and `next.alias` are aliases.

`anim` names the glTF animation in `model_NNN.glb`: `motion_NNN` (own bank) or `common_NNN`.

`attack.frames[k].segments` are 1-2 segments `[[x,y,z],[x,y,z]]` per active frame in character space
(attacker at the origin facing 0, +Z towards the opponent). Place them with `root + RotY(-facing)·p`.
They are pre-scaled to the owner's model size; `alt_frames` (100 % scale) are used when the attacker is
Ogre or Mokujin. Segments have no radius: test them against the defender's hurt spheres as vertical
cylinders (see rules.json).

## Cancel lists
`moves[i].cancel_start` indexes `cancels`; a list runs until an `END` entry (cmd 0xC000, whose `dest`
is the move played at animation end and whose `win_start` is the first actionable frame).
`kind == "call"` jumps to `shared.json shared_cancels.entries[shared_list_start]` until a `return`.
Entry fields: input must match (`input`/`cmd`), `win_start <= frame <= win_end`, `req` gate,
`cond` (conds >= 0x45 are only checked on the frame you are struck: parries/reversals), then the move
`dest` is queued and committed at frame `exec` (255 = animation end).

Input notation: numpad directions as `d/b d d/f b n f u/b u u/f`, buttons 1-4 (1 = LP, 2 = RP,
3 = LK, 4 = RK). `a|b` = either direction, `(1|2)` = any of the buttons, `*` = any direction,
`qcf`/`qcb`/`hcf`/`hcb` = motions, `dash`/`backdash` = f,n,f / b,n,b within 19 frames. Exact step
data for sequences is in `shared.json sequences`.

## Uncertain / guessed
- Names marked `ai_*` and `state_*`/`bitN`/`unknown_*` are AI hints or unidentified bits (kept raw).
- Throw direction names (`side_1`/`side_2`) follow move-properties.md; the left/right meaning of
  quadrants 1/3 is unknown.
- Most of the 44 transition types are only partially named; `transition_type` is the raw value.
- `camera_keyframes_hex` (header +0x24): the camera motions the selectors point at (value bit 31) are decoded into
  `camera_motions`; the rest of the block is kept raw.
- Frame advantage derived from END windows may be off by one frame.
"#;

pub fn main(args: &[String]) -> Result<()> {
    let [src, outdir, ..] = args else { bail!("{USAGE}") };
    run(&Ctx { out: &StdFs(outdir.into()), log: &print_line, jobs: 1 }, &StdDisc(src.into()), "")
}

/// Writes `outdir`/gamedata/.
pub fn run(ctx: &Ctx, disc: &dyn DiscFile, outdir: &str) -> Result<()> {
    let out = &join(outdir, "gamedata");
    let game = Game::load(disc)?;
    let rec = &game.rec;
    let exe = Exe::new(&game.exe);
    let seqs = read_sequences(&exe)?;
    let mut sizes = BTreeMap::new();
    let mut put = |name: &str, obj: Value| -> Result<()> {
        sizes.insert(name.to_string(), write_json(ctx.out, &join(out, name), &obj)?);
        Ok(())
    };

    // ---- movesets
    let common = Moveset::new(&rec[279], exe, &seqs, None, true, None)?;
    let pack_by_md5: BTreeMap<String, usize> =
        (280..301).filter(|&n| !rec[n].is_empty()).map(|n| (md5_hex(&rec[n]), n)).collect();
    let pack = |k: &str| pack_by_md5.get(k).map_or(Value::Null, |&n| json!(n));
    // md5 -> the records with it, in first-seen order (a Python dict)
    let mut by_md5: Vec<(String, Vec<usize>)> = Vec::new();
    let mut models = Vec::new();
    for m in (71..276).step_by(4) {
        let d = &rec[m + 3];
        let k = md5_hex(d);
        match by_md5.iter_mut().find(|e| e.0 == k) {
            Some(e) => e.1.push(m + 3),
            None => by_md5.push((k.clone(), vec![m + 3])),
        }
        models.push((m, k, *d.get(1).context("a moveset record is empty")?));
    }
    let (mut files, mut loaded): (Vec<(String, String)>, Vec<Moveset>) = (Vec::new(), Vec::new());
    for (k, recs) in &by_md5 {
        let ms = Moveset::new(&rec[recs[0]], exe, &seqs, Some(&common), false, None)?;
        let fname = format!("moveset_{:02}.json", ms.moveset_id);
        if files.iter().any(|f| f.1 == fname) {
            bail!("two movesets would be written as {fname}");
        }
        put(&format!("movesets/{fname}"), ms.export(json!({"character_records": recs, "pack_record": pack(k)}))?)?;
        files.push((k.clone(), fname));
        loaded.push(ms);
    }
    put("movesets/common.json", common.export(json!({"record": 279}))?)?;
    // the attract embu's own set (overlay record 0, loaded at 0x800B8D58; set at 0x800DD818, size = header word 11)
    let r0 = &rec[0];
    let off = 0x800DD818 - 0x800B8D58;
    let size = Exe::with_base(r0, 0).u32(off as i64 + 44)? as usize;
    let embu = Moveset::new(py_slice(r0, off, off + size), exe, &seqs, Some(&common), false, Some("embu"))?;
    put("movesets/moveset_embu.json", embu.export(json!({"record": 0, "address": "0x800DD818"}))?)?;
    let file_of = |k: &str| files.iter().find(|f| f.0 == k).map(|f| f.1.clone()).unwrap_or_default();
    let model_file: BTreeMap<i64, String> =
        models.iter().map(|(m, k, _)| (*m as i64, format!("movesets/{}", file_of(k)))).collect();
    let mut names: Vec<String> = files.iter().map(|f| f.1.clone()).collect();
    names.sort();
    let index: Vec<Value> = models
        .iter()
        .map(|(m, k, mid)| {
            json!({"model_record": m, "moveset_record": m + 3, "glb": format!("model_{m:03}.glb"),
                   "moveset_file": file_of(k), "moveset_id": mid, "pack_record": pack(k)})
        })
        .collect();
    put(
        "movesets/index.json",
        json!({"models": index, "files": names, "common": "common.json",
               "note": "Pack records 280..300 (moveset id = record - 280; 295 empty) equal the m+3 records of that moveset."}),
    )?;

    // ---- EXE tables
    put("shared.json", t::shared(&exe, &seqs)?)?;
    put("reactions.json", t::reactions(&exe)?)?;
    put("rules.json", t::rules(&exe)?)?;
    put("roster.json", t::roster(&exe, rec, &model_file)?)?;
    put("stages.json", t::stages(&exe)?)?;
    put("music.json", t::music(&exe)?)?;
    put("ai.json", t::ai(&exe, rec)?)?;
    put("camera.json", t::camera(&exe)?)?;
    put("sound.json", t::sound(&exe)?)?;
    put("screens.json", t::screens(&exe, rec)?)?;
    put("scenes.json", t::scenes(&exe, rec)?)?;
    put("attract.json", t::attract(&exe, rec)?)?;
    put("ball.json", t::ball(&exe, rec)?)?;
    put("faces.json", t::faces(&exe)?)?;
    put("force.json", t::force(&exe, rec)?)?;
    put("rumble.json", t::rumble(&exe)?)?;
    ctx.out.write(&join(out, "README.md"), README.as_bytes())?;

    // ---- validation
    let mut sets: Vec<(&str, usize)> =
        files.iter().zip(&loaded).map(|(f, ms)| (f.1.as_str(), ms.motions.len())).collect();
    sets.push(("common.json", common.motions.len()));
    let paul = files.iter().position(|f| f.1 == "moveset_00.json").map(|i| &loaded[i]);
    let ok = validate(ctx, out, paul, &sets, common.motions.len())?;
    let total: usize = sizes.values().sum();
    ctx.log(&format!("\n{} JSON files, {:.2} MB", sizes.len(), total as f64 / 1e6));
    for (n, z) in &sizes {
        ctx.log(&format!("  {n:32} {:9.1} KB", *z as f64 / 1024.0));
    }
    if !ok {
        bail!("validation failed");
    }
    Ok(())
}

/// `sets`: (moveset file, its motion count) of every exported character set and common.json.
fn validate(ctx: &Ctx, out: &str, paul_ms: Option<&Moveset>, sets: &[(&str, usize)], n_common: usize) -> Result<bool> {
    let load = |path: &str| -> Result<Value> {
        let p = join(out, path);
        serde_json::from_str(&ctx.out.read_string(&p)?).with_context(|| format!("{p} does not load back"))
    };
    let mut ok = true;
    let mut check = |cond: bool, msg: String| {
        ctx.log(&format!("{}{msg}", if cond { "  ok   " } else { "  FAIL " }));
        ok &= cond;
    };
    ctx.log("validation:");
    // every JSON loads back
    let mut n = 0;
    for sub in ["", "movesets"] {
        for e in ctx.out.list(&join(out, sub))? {
            if !e.is_dir && e.name.ends_with(".json") {
                load(&join(sub, &e.name))?;
                n += 1;
            }
        }
    }
    check(true, format!("{n} JSON files load back"));
    let paul = load("movesets/moveset_00.json")?;
    let via = |alias: usize| {
        let a = &paul["aliases"][alias];
        if a["bank"] == "own" { paul["moves"][a["move"].as_u64().unwrap_or(0) as usize].clone() } else { Value::Null }
    };
    let (jab, d4) = (via(0x127), via(0x164));
    check(
        jab["index"] == 104
            && jab["damage"] == 5
            && jab["attack_mask"]["level_name"] == "high"
            && jab["active"] == json!([8, 8])
            && jab["frames"] == 37,
        format!(
            "Paul 1 (alias 0x127 -> move {}): dmg {} {} active {} frames {} anim {}",
            jab["index"],
            jab["damage"],
            s(&jab["attack_mask"]["level_name"]),
            list(&jab["active"]),
            jab["frames"],
            s(&jab["anim"])
        ),
    );
    let anim_ok = paul_ms.is_some_and(|p| {
        let w0 = Exe::with_base(p.d, 0).u32(p.h[2] + 56 * 104).unwrap_or(-1);
        let idx: usize = s(&jab["anim"]).get(7..).and_then(|x| x.parse().ok()).unwrap_or(usize::MAX);
        p.motions.get(idx).is_some_and(|&o| o as i64 == (w0 & 0x3FFFFFFF) + p.h[7])
    });
    check(anim_ok, "Paul 1 anim offset matches find_motions".into());
    check(
        d4["damage"] == 15 && d4["attack_mask"]["level_name"] == "low" && d4["active"] == json!([14, 14]),
        format!(
            "Paul d+4 (alias 0x164 -> move {}): dmg {} {} active {} frames {}",
            d4["index"],
            d4["damage"],
            s(&d4["attack_mask"]["level_name"]),
            list(&d4["active"]),
            d4["frames"]
        ),
    );
    let seg = &jab["attack"]["frames"][0]["segments"][0];
    check(
        seg[1] == json!([23, -1411, 1296]),
        format!("Paul 1 segment end {} (attack-paths.md: (23,-1411,1296))", list(&seg[1])),
    );
    let start = jab["cancel_start"].as_u64().unwrap_or(0) as usize;
    let cancels = paul["cancels"].as_array().map_or(&[][..], |c| &c[start.min(c.len())..(start + 40).min(c.len())]);
    let jab_cancel = cancels.iter().find(|c| c["input"] == "2" && c["win_start"] == 1);
    check(jab_cancel.is_some_and(|c| c["exec"] == 8), "Paul 1 -> 2 accepted from frame 1, exec 8".into());
    let (mut bad, mut n) = (0, 0);
    for &(fname, own) in sets {
        let j = load(&join("movesets", fname))?;
        for mv in j["moves"].as_array().into_iter().flatten() {
            n += 1;
            let anim = mv["anim"].as_str();
            let lim = if anim.is_some_and(|a| a.starts_with("common")) { n_common } else { own };
            let idx = anim.and_then(|a| a.split('_').nth(1)).and_then(|x| x.parse::<usize>().ok());
            if idx.is_none_or(|i| i >= lim) {
                bad += 1;
            }
        }
        if j["aliases"].as_array().is_some_and(|a| a.len() != N_ALIASES) {
            bad += 1;
        }
    }
    check(bad == 0, format!("{n} moves in {} files: every anim name resolves ({bad} bad)", sets.len()));
    let shared = load("shared.json")?;
    let qcf = shared["sequences"]["entries"].as_array().into_iter().flatten().find(|e| e["cmd"] == 0xC011);
    let qcf = qcf.map_or("", |e| s(&e["input"]));
    check(qcf == "qcf+1+2", format!("sequence 0xC011 reads \"{qcf}\""));
    let rules = load("rules.json")?;
    check(
        rules["health"]["default_max"] == 130 && rules["damage_zones"]["percent"][11] == 140,
        "max health 130, damage zone 11 = 140%".into(),
    );
    Ok(ok)
}

fn s(v: &Value) -> &str {
    v.as_str().unwrap_or("None")
}

/// A list as Python prints it: `[8, 8]`.
fn list(v: &Value) -> String {
    crate::pyjson::to_string(v, crate::pyjson::DEFAULT)
}
